/*
 * Builds the homepage hero art for the site: bundles art/src/canvas-core/heroPlant.ts (the anidoodle source,
 * brief in art/brief.md) with the art project's own esbuild into one dependency-free module,
 * src/sections/hero/plant.gen.js, typed by plant.gen.d.ts. The site draws it on a canvas
 * (src/sections/hero/HeroPlant.tsx). Rerun after changing the art:
 *
 *   npm run hero:art        (needs `npm install` in art/ once)
 *
 * The output is committed, so the site builds without the art project's dependencies.
 */
import { createRequire } from 'node:module';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(root, 'art', 'package.json'));
const esbuild = require('esbuild');

await esbuild.build({
  entryPoints: [path.join(root, 'art/src/canvas-core/heroPlant.ts')],
  outfile: path.join(root, 'src/sections/hero/plant.gen.js'),
  bundle: true,
  format: 'esm',
  target: 'es2020',
  minify: true,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/hero-art.mjs from art/src/canvas-core/heroPlant.ts (anidoodle, Apache-2.0 engine). Do not edit.' },
});
console.log('hero art -> src/sections/hero/plant.gen.js');
